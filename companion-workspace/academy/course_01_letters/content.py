def arabic_block(text: str, reference: str | None = None) -> str:
    label = f"\n\n*{reference}*" if reference else ""
    return f'<div dir="rtl" lang="ar" style="font-size:2rem;line-height:2.1;text-align:center">{text}</div>{label}'


def forms_table(letters: list[str]) -> str:
    rows = [
        "| Буква | Отдельно | В начале | Внутри | В конце | Соединение |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for letter in letters:
        isolated, initial, medial, final, note = LETTER_FORMS[letter]
        rows.append(f"| {letter} | {isolated} | {initial} | {medial} | {final} | {note} |")
    return "\n".join(rows)


def lesson(title: str, body: str, *, preview: bool = False, notes: str = "") -> dict:
    return {
        "title": title,
        "body": body.strip(),
        "include_in_preview": 1 if preview else 0,
        "instructor_notes": (notes or "Попросите ученика сначала указать букву глазами, затем назвать её. Не засчитывайте угадывание по месту в алфавите. Произношение корректируйте только по проверенной модели учителя.").strip(),
    }


def letter_forms_lesson(title: str, letters: list[str], focus: str) -> dict:
    symbols = " · ".join(letters)
    body = f"""
## Цель урока

Узнать буквы **{symbols}** независимо от того, стоят они отдельно, в начале, внутри или в конце слова.

## Карта форм

{forms_table(letters)}

Удлинительная черта **ـ** здесь служит только учебной опорой: она показывает, с какой стороны буква соединена. В мусхафе длина соединения меняется вместе со шрифтом, но каркас буквы и точки остаются узнаваемыми.

## На что смотреть

{focus}

## Узнай без подсказки

1. Закрой первый столбец таблицы.
2. Для каждой формы назови базовую букву.
3. Перемешай порядок: читай справа налево и слева направо.
4. Отметь одну пару, которую пока путаешь. Она вернётся в следующем уроке.

## Готовность

Переходите дальше, когда ученик узнаёт не менее 8 из 10 случайно показанных форм без перебора алфавита.
"""
    return lesson(title, body)


def quran_hunt_lesson(title: str, targets: list[str], passages: list[tuple[str, str]], prompts: list[str]) -> dict:
    target_line = " · ".join(targets)
    rendered = "\n\n".join(arabic_block(text, reference) for reference, text in passages)
    prompt_text = "\n".join(f"{index}. {prompt}" for index, prompt in enumerate(prompts, start=1))
    body = f"""
## Поиск в Коране

Сегодня ищем только знакомые буквы: **{target_line}**. Остальные знаки пока можно пропускать.

{rendered}

## Маршрут взгляда

{prompt_text}

## Проверка по памяти

Закройте карту форм и ещё раз найдите каждую целевую букву. Для одного примера скажите, где она стоит: отдельно, в начале, внутри или в конце слова.

## Важно

Цель этого задания — распознавание письма. Полное чтение аята, огласовки, махрадж и правила таджвида изучаются отдельно и проверяются по достоверной аудиомодели или с преподавателем.
"""
    return lesson(title, body)


